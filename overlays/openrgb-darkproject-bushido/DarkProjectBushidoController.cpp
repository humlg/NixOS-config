DarkProjectBushidoController::DarkProjectBushidoController(hid_device* dev_handle, const char* path, std::string dev_name)
{
    dev                 = dev_handle;
    location            = path;
    name                = dev_name;
}

DarkProjectBushidoController::~DarkProjectBushidoController()
{
    hid_close(dev);
}

std::string DarkProjectBushidoController::GetLocation()
{
    return("HID: " + location);
}

std::string DarkProjectBushidoController::GetName()
{
    return(name);
}

std::string DarkProjectBushidoController::GetSerial()
{
    wchar_t serial_string[128];
    int ret = hid_get_serial_number_string(dev, serial_string, 128);

    if(ret != 0)
    {
        return("");
    }

    return(StringUtils::wstring_to_string(serial_string));
}

void DarkProjectBushidoController::SetColor(RGBColor color)
{
    unsigned char color_packet[DARKPROJECTBUSHIDO_PACKET_SIZE];
    memcpy(color_packet, color_packet_template, DARKPROJECTBUSHIDO_PACKET_SIZE);

    color_packet[DARKPROJECTBUSHIDO_RED_BYTE]      = RGBGetRValue(color);
    color_packet[DARKPROJECTBUSHIDO_GREEN_BYTE]    = RGBGetGValue(color);
    color_packet[DARKPROJECTBUSHIDO_BLUE_BYTE]     = RGBGetBValue(color);

    hid_send_feature_report(dev, prime_packet, DARKPROJECTBUSHIDO_PACKET_SIZE);
    hid_send_feature_report(dev, color_packet, DARKPROJECTBUSHIDO_PACKET_SIZE);
}
